  function exchange(body) {
    return discover().then(function (meta) {
      return fetch(meta.token_endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
        body: form(body)
      }).then(function (res) {
        return jsonOrText(res).then(function (p) {
          if (!res.ok || !p.body || !p.body.access_token) throw apiError(res, p);
          const prev = tokens() || {};
          const t = {
            access_token: p.body.access_token,
            /* A refresh response that rotates the token replaces it; one that
             * does not must not blank the one we hold. */
            refresh_token: p.body.refresh_token || prev.refresh_token || '',
            expires_at: Date.now() + (((p.body.expires_in | 0) || 3600) * 1000),
            email: prev.email || ''
          };
          setTokens(t);
          return t;
        });
      });
    });
  }

  let refreshing = null;

  /* A live access token, refreshed 60s before it lapses. Rejects — it never
   * opens a popup on its own — so the caller can say "sign in again" instead
   * of a window appearing out of nowhere mid-generation. */
  function accessToken() {
    const t = tokens();
    if (!t || !t.access_token) return Promise.reject(new Error('Not signed in to ImagineArt.'));
    if (Date.now() < (t.expires_at || 0) - 60000) return Promise.resolve(t.access_token);
    if (!t.refresh_token) return Promise.reject(sessionOver());
    if (refreshing) return refreshing;
    refreshing = discover().then(function (meta) {
      return clientId(meta);
    }).then(function (cid) {
      return exchange({
        grant_type: 'refresh_token',
        refresh_token: t.refresh_token,
        client_id: cid,
        resource: RESOURCE,
        scope: SCOPE
      });
    }).then(function (fresh) {
      refreshing = null;
      return fresh.access_token;
    }).catch(function (e) {
      refreshing = null;
      setTokens(null);
      throw sessionOver(e);
    });
    return refreshing;
  }

  function sessionOver(e) {
    const err = new Error('The ImagineArt session has expired — sign in again in Settings → ImagineArt.');
    err.auth = true;
    err.cause = e;
    return err;
  }

  /* ---------------- sign in ---------------- */

  let signingIn = null;

  function signIn() {
    const why = signInBlocked();
    if (why) return Promise.reject(new Error(why));
    if (signingIn) return signingIn;

    const uri = redirectUri();
    const state = randomString(16);
    const verifier = randomString(48);

    /* The popup is opened synchronously, inside the click, or the browser
     * blocks it — the URL is filled in once discovery answers. */
    const win = window.open('', 'imagine-signin',
      'width=520,height=760,menubar=no,toolbar=no');
    if (!win) return Promise.reject(new Error('The sign-in window was blocked — allow popups for this page and try again.'));

    signingIn = Promise.all([discover(), sha256(verifier)]).then(function (both) {
      const meta = both[0], challenge = both[1];
      return clientId(meta).then(function (cid) {
        const url = meta.authorization_endpoint + '?' + form({
          response_type: 'code',
          client_id: cid,
          redirect_uri: uri,
          scope: SCOPE,
          state: state,
          code_challenge: challenge,
          code_challenge_method: 'S256',
          /* RFC 8707 — says out loud which resource the token is for. */
          resource: RESOURCE
        }).toString();
        win.location = url;
        return awaitCode(win, state).then(function (code) {
          return exchange({
            grant_type: 'authorization_code',
            code: code,
            redirect_uri: uri,
            client_id: cid,
            code_verifier: verifier,
            resource: RESOURCE
          });
        });
      });
    }).then(function (t) {
      signingIn = null;
      return whoAmI().catch(function () { return null; })
        .then(function () { return refreshCatalog().catch(function () { return null; }); })
        .then(function () { return t; });
    }).catch(function (e) {
      signingIn = null;
      try { win.close(); } catch (x) { }
      throw e;
    });

    return signingIn;
  }

  /* Wait for the popup to hand back a code. Three ways this ends: the message
   * arrives, the user closes the window, or nothing happens for five minutes. */
  function awaitCode(win, state) {
    return new Promise(function (resolve, reject) {
      let done = false;
      const finish = function (fn, arg) {
        if (done) return;
        done = true;
        window.removeEventListener('message', onMsg);
        clearInterval(watch);
        clearTimeout(cap);
        fn(arg);
      };
      const onMsg = function (ev) {
        if (ev.origin !== location.origin) return;
        const d = ev.data;
        if (!d || d.sb !== 'imagine-oauth') return;
        if (d.error) {
          finish(reject, new Error(d.errorDescription || d.error));
          return;
        }
        if (d.state !== state) {
          finish(reject, new Error('The sign-in came back with the wrong state — it was not the window we opened.'));
          return;
        }
        finish(resolve, d.code);
      };
      window.addEventListener('message', onMsg);
      const watch = setInterval(function () {
        if (win.closed) finish(reject, new Error('Sign-in was cancelled.'));
      }, 500);
      const cap = setTimeout(function () {
        try { win.close(); } catch (e) { }
        finish(reject, new Error('Sign-in timed out.'));
      }, 5 * 60 * 1000);
    });
  }

  /* ---------------- who, and how many credits ---------------- */

  let acct = null;   // { email, credits, at }

  function account() { return acct; }

  function whoAmI() {
    return Promise.all([discover(), accessToken()]).then(function (both) {
      const meta = both[0], tok = both[1];
      const ep = meta.userinfo_endpoint || AS_FALLBACK.userinfo_endpoint;
      return fetch(ep, { headers: { Authorization: 'Bearer ' + tok, Accept: 'application/json' } })
        .then(function (res) {
          return jsonOrText(res).then(function (p) {
            if (!res.ok || !p.body) throw apiError(res, p);
            const email = p.body.email || p.body.sub || '';
            const t = tokens();
            if (t) { t.email = email; lsSet(K_TOK, t); }
            acct = { email: email, credits: acct && acct.credits, at: Date.now() };
            notify();
            return acct;
          });
        });
    });
  }

  /* Credits are a tool call, not an endpoint — ImagineArt exposes "balance
   * inquiry" through MCP. Best effort: a number if it can be found, nothing if
   * it cannot. Never blocks a generation. */
  function balance() {
    if (!orgId()) return Promise.resolve(acct);
    const ask = toolNamed(TOOL.balance)
      ? callRaw(TOOL.balance, { org_id: orgId() })
      /* a server that does not publish get_balance falls back to the scored
         picker, which is what that machinery is still for */
      : callTool('balance', {});
    return ask.then(function (out) {
      const n = firstNumber(out.text || '') ;
      acct = acct || { email: (tokens() || {}).email || '' };
      if (n !== null) acct.credits = n;
      acct.at = Date.now();
      notify();
      return acct;
    }).catch(function () { return acct; });
  }

  function firstNumber(s) {
    const m = /(-?\d[\d,]*(?:\.\d+)?)/.exec(String(s).replace(/\s+/g, ' '));
    if (!m) return null;
    const n = parseFloat(m[1].replace(/,/g, ''));
    return isFinite(n) ? n : null;
  }

  /* ---------------- MCP transport ----------------
   *
   * Streamable HTTP: one POST per JSON-RPC message, and the answer comes back
   * either as a JSON body or as an SSE stream carrying the same object. Both
   * are handled here so nothing above this cares.
   */
  const mcp = { session: null, ready: null, tools: null, id: 0 };

  /* ---- the headers a browser is actually allowed to send ----
   *
   * mcp.imagine.art answers a preflight with a FIXED allow-list, and neither
   * MCP-Protocol-Version nor Mcp-Session-Id is on it. A browser will not send
   * a non-safelisted header that the server has not allowed, so the preflight
   * fails and fetch rejects before the request exists — the handshake failing
   * with nothing in any log, because nothing was ever sent. curl has no such
   * rule, which is why probing from a terminal said the endpoint was fine.
   *
   * So the protocol version travels where it also belongs, in the initialize
   * params, and the session id is not sent at all — it could not be read back
   * either, since mcp-session-id is not in the server's expose-headers. That
   * makes this a stateless client, which the transport allows.
   *
   * Accept is CORS-safelisted, Content-Type and Authorization are both on the
   * server's list, so what is left preflights cleanly. */
  function mcpPost(msg) {
    return accessToken().then(function (tok) {
      const headers = {
        'Content-Type': 'application/json',
        Accept: 'application/json, text/event-stream',
        Authorization: 'Bearer ' + tok
      };
      return fetch(RESOURCE, { method: 'POST', headers: headers, body: JSON.stringify(msg) })
        .catch(function (e) {
          /* A rejected fetch means it never left the browser. Against this
           * host that is nearly always CORS, and a bare "Failed to fetch" is
           * the least helpful sentence available. */
          const err = new Error('The request never left the browser — ' +
            'ImagineArt\u2019s server did not allow it from this page (CORS). ' +
            (e && e.message ? '[' + e.message + ']' : ''));
          err.cors = true;
          throw err;
        })
        .then(function (res) {
          const sid = res.headers.get('mcp-session-id');
          if (sid) mcp.session = sid;
          if (res.status === 202) return null;          // notification accepted
          return res.text().then(function (text) {
            const obj = parseRpc(text, msg.id);
            if (!res.ok) {
              if (res.status === 401 || res.status === 403) {
                /* The session died under us; a retry after a refresh is the
                 * caller's business, not this layer's. */
                const e = new Error('ImagineArt refused the token.');
                e.auth = true; e.status = res.status;
                throw e;
              }
              throw apiError(res, { body: obj && obj.error, text: text });
            }
            if (obj && obj.error) {
              const e = new Error(obj.error.message || 'ImagineArt returned an error.');
              e.code = obj.error.code;
              throw e;
            }
            return obj ? obj.result : null;
          });
        });
    });
  }

  /* A JSON body, or an SSE stream of them — take the frame that answers our id
   * (or the last one that carries a result, for a server that streams). */
  function parseRpc(text, id) {
    const t = String(text || '').trim();
    if (!t) return null;
    if (t.charAt(0) === '{' || t.charAt(0) === '[') {
      try {
        const j = JSON.parse(t);
        return Array.isArray(j) ? (j.filter(function (x) { return x.id === id; })[0] || j[0]) : j;
      } catch (e) { return null; }
    }
    /* A stream may carry messages that are not ours — the protocol allows it
       — so the frame answering our id wins outright, and anything else is
       only a fallback for a server that does not echo the id. */
    let mine = null, other = null;
    t.split(/\r?\n/).forEach(function (line) {
      const m = /^data:\s*(.*)$/.exec(line);
      if (!m || !m[1] || m[1] === '[DONE]') return;
      let j = null;
      try { j = JSON.parse(m[1]); } catch (e) { return; }
      if (!j) return;
      if (j.id === id) mine = j;
      else if (j.id === undefined && (j.result || j.error)) other = j;
    });
    return mine || other;
  }

  function mcpReady() {
    if (mcp.ready) return mcp.ready;
    mcp.ready = mcpPost({
      jsonrpc: '2.0', id: ++mcp.id, method: 'initialize',
      params: {
        /* the only place the version can travel: the header a browser would
           normally carry it in is not one this server allows */
        protocolVersion: MCP_PROTOCOL,
        capabilities: {},
        clientInfo: { name: CLIENT_NAME, version: String(window.SB_BUILD || 'dev') }
      }
    }).then(function (r) {
      /* The notification is fire-and-forget; a server that does not want it
       * answers 202 or 404 and neither is worth failing over. */
      return mcpPost({ jsonrpc: '2.0', method: 'notifications/initialized', params: {} })
        .catch(function () { return null; })
        .then(function () { return r; });
    }).catch(function (e) {
      mcp.ready = null;
      throw e;
    });
    return mcp.ready;
  }

  function toolList(force) {
    if (mcp.tools && !force) return Promise.resolve(mcp.tools);
    return mcpReady().then(function () {
      return mcpPost({ jsonrpc: '2.0', id: ++mcp.id, method: 'tools/list', params: {} });
    }).then(function (r) {
      mcp.tools = (r && r.tools) || [];
      notify();
      return mcp.tools;
    });
  }

  /* ---------------- the tools ImagineArt actually publishes ----------------
   *
   * Read off a real account's tools/list rather than guessed at. The shape is
   * not what a generic binder would have produced, and three things about it
   * decide how everything below works:
   *
   *   org_id is required on every generation. ImagineArt users can belong to
   *   several organizations and a generation is attributed to one, so nothing
   *   can be made until one is chosen. select_organization lists them; the
   *   server is stateless, so the id rides on every later call.
   *
   *   generation is asynchronous. Both generators return a uuid immediately
   *   and fetch_status reports on it — with sync:true it waits server-side
   *   for about 45 seconds, which turns a poll loop into a few long calls.
   *
   *   a reference image is a URL, never bytes. generate_image takes one
   *   image_url; generate_video takes an ARRAY, where one entry means
   *   animate-this-still and two or more mean reference-to-video. Our frames
   *   are local, so they have to be uploaded first — user_upload takes a file
   *   and an org_id and hands back a URL.
   *
   * The model lists are in the tool descriptions rather than in an enum, so
   * they are parsed from there: "model (optional) — one of: "a", "b", …".
   */
  const TOOL = {
    image: 'generate_image',
    video: 'generate_video',
    status: 'fetch_status',
    upload: 'user_upload',
    orgs: 'select_organization',
    balance: 'get_balance'
  };

  function toolNamed(name) {
    return (mcp.tools || []).filter(function (t) { return t.name === name; })[0] || null;
  }

  /* The models a tool says it takes, in the order it lists them — the first
   * is the one ImagineArt defaults to. */
  function modelsFromTool(name) {
    const t = toolNamed(name);
    const d = (t && t.description) || '';
    const m = /model \(optional\)[^:]*:([\s\S]*?)\. Pass the/.exec(d);
    if (!m) return [];
    const out = [];
    const re = /"([^"]+)"/g;
    let hit;
    while ((hit = re.exec(m[1]))) if (out.indexOf(hit[1]) < 0) out.push(hit[1]);
    return out;
  }

  /* Which aspect ratios and durations a given model will accept, off the same
   * description — so a board asking for 21:9 on a model that only does 16:9
   * can be told rather than silently downgraded. */
  function allowFor(name, model, what) {
    const t = toolNamed(name);
    const d = (t && t.description) || '';
    const esc = model.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

    /* The tables read:
     *   resolution (optional) - ...
     *     Per-model allow-lists (first value is the default ...):
     *       - ltx-2.3:  1080p, 1440p, 2160p
     * and the parenthetical is not always there. */
    const sect = new RegExp(what + ' \\(optional\\)[\\s\\S]*?allow-lists[^:\n]*:([\\s\\S]*?)(?:\n\\s*\u2022|$)')
      .exec(d);
    if (sect) {
      const line = new RegExp('-\\s*' + esc + ':\\s*([^\n]+)').exec(sect[1]);
      if (line) {
        if (/\(none/.test(line[1])) return [];
        return line[1].split(',').map(function (x) { return x.trim(); })
          .filter(function (x) { return x && !/^\(/.test(x); });
      }
      /* named on a shared line: "- kling-2.6-pro, kling-o3, wan-2.2: (none ...)" */
      const shared = new RegExp('-\\s*[^\n]*\\b' + esc + '\\b[^\n]*:\\s*([^\n]+)').exec(sect[1]);
      if (shared) {
        if (/\(none/.test(shared[1])) return [];
        return shared[1].split(',').map(function (x) { return x.trim(); })
          .filter(function (x) { return x && !/^\(/.test(x) && !/^[a-z0-9_.-]+$/.test(x) === false ? true : false; });
      }
      return null;
    }

    /* quality is a sentence, not a table: 'only gpt-image-2 supports it:
     * "low", "medium", "high"'. */
    const one = new RegExp(what + ' \\(optional\\)[\\s\\S]{0,200}?' + esc +
      ' supports it:([^\u2022]{0,120})').exec(d);
    if (one) {
      const vals = (one[1].match(/"([^"]+)"/g) || []).map(function (x) { return x.replace(/"/g, ''); });
      if (vals.length) return vals;
    }
    return null;
  }

  /* ---------------- resolution ----------------
   *
   * Every generator takes one, every model publishes what it will accept,
   * and the first value on that list is what you get when you send nothing —
   * which is what this app always did. That is not a neutral default: it is
   * the model's floor. Seedance has been making 480p, Veo 720p, the stills
   * 1K, and gpt-image-2 at "low" quality, all silently.
   *
   * So a board says what it wants once and every model is asked for the
   * nearest thing it has.
   */
  const RES_RANK = {
    '360p': 360, '480p': 480, '540p': 540, '720p': 720, '768p': 768,
    '1080p': 1080, '1440p': 1440, '2160p': 2160, '4k': 2160,
    '1k': 1080, '2k': 1440, '3k': 2880
  };

  function rank(v) {
    const k = String(v || '').trim().toLowerCase();
    if (RES_RANK[k]) return RES_RANK[k];
    const n = parseInt(k, 10);
    return isFinite(n) ? n : 0;
  }

  function policy(p) {
    const v = p && p.settings && p.settings.imagineResolution;
    return (v === '1080p' || v === 'default') ? v : 'best';
  }

  /* The resolution to ask this model for, or '' to send nothing — which is
   * the honest answer both for "leave it alone" and for a model that ignores
   * the field. */
  function resolutionFor(p, slug, kind) {
    if (policy(p) === 'default') return '';
    const list = allowFor(kind === 'image' ? TOOL.image : TOOL.video, slug, 'resolution');
    if (!list || !list.length) return '';
    const sorted = list.slice().sort(function (a, b) { return rank(a) - rank(b); });
    if (policy(p) === 'best') return sorted[sorted.length - 1];
    /* 1080p where it is offered, otherwise the best below it — and the
     * smallest available if even that is above 1080p. */
    const under = sorted.filter(function (v) { return rank(v) <= 1080; });
    return under.length ? under[under.length - 1] : sorted[0];
  }

  /* Only gpt-image-2 takes one, and its floor is "low". */
  function qualityFor(p, slug) {
    if (policy(p) === 'default') return '';
    const list = allowFor(TOOL.image, slug, 'quality');
    if (!list || !list.length) return '';
    const best = ['high', 'medium', 'low'].filter(function (q) { return list.indexOf(q) >= 0; })[0];
    return best || '';
  }

  /* ---------------- what it costs ----------------
   *
   * Two figures, and they are told apart wherever they are shown. The
   * published one is ImagineArt's base price: the model at its minimum
   * duration and default settings, which is a floor for anything longer or
   * larger. The measured one is the difference in the account balance either
   * side of a real generation at exactly these settings, which is the truth
   * and is worth more than any table.
   */
  function costKey(slug, duration, res) {
    return [slug || '', duration || '', res || ''].join('|');
  }

  function measured() {
    const all = lsGet(K_COST) || {};
    return all[catKey()] || {};
  }

  function noteCost(slug, duration, res, credits) {
    if (!(credits > 0)) return;
    const all = lsGet(K_COST) || {};
    const mine = all[catKey()] || {};
    mine[costKey(slug, duration, res)] = { credits: credits, at: Date.now() };
    all[catKey()] = mine;
    lsSet(K_COST, all);
  }

  function published(slug) {
    const table = (SB.ImagineModels && SB.ImagineModels.credits) || {};
    return table[slug] || null;
  }

  /* {credits, from: 'measured'|'published', note} or null when nothing is
   * known — in which case the UI says nothing rather than guessing. */
  function costFor(slug, duration, res) {
    const mine = measured()[costKey(slug, duration, res)];
    if (mine) return { credits: mine.credits, from: 'measured' };
    const pub = published(slug);
    if (!pub) return null;
    const tier = pub.tiers && res ? pub.tiers[String(res).toUpperCase()] : null;
    return {
      credits: tier || pub.base,
      from: 'published',
      note: 'base price — longer or larger costs more'
    };
  }

  /* The balance, as a number, for measuring against. Best effort. */
  function balanceNow() {
    if (transport() === 'key' || !isSignedIn() || !orgId()) return Promise.resolve(null);
    return callRaw(TOOL.balance, { org_id: orgId() }).then(function (got) {
      const n = firstNumber(got.text || JSON.stringify((got.raw || {}).structuredContent || {}));
      return n;
    }).catch(function () { return null; });
  }

  /* ---------------- what travels with the board ----------------
   *
   * The model list, the slug for each model, which two are selected, the
   * aspect ratio and the resolution policy have always been project state,
   * so they already travel. What did not was everything the app learned
   * about an account: the catalog it read, the prices it measured, and which
   * organization the work was billed to. Those are facts about how this
   * board is made rather than about who is making it, so they belong in the
   * file too — and then one person can set a board up and hand it over.
   *
   * The token and the API key are the line that does not move. A .storyboard
   * gets emailed; a credential in one is a credential in somebody's mail
   * archive forever.
   */
  /* Written on Save — but never to less than is already there. Every
   * teammate presses Save eventually, and doing it while signed out used to
   * replace the setup with an empty one: the catalog snapshot, the measured
   * prices and the organization all gone from the file, for everybody. So
   * each field is only replaced by something, and the stamp only moves when
   * something actually changed. */
  function publishToBoard(p) {
    if (!p || !p.settings) return null;
    const was = (p.settings.imagine && typeof p.settings.imagine === 'object')
      ? p.settings.imagine : {};
    const share = p.settings.imagineShareOrg !== false;
    const t = tokens() || {};
    const mineCat = (cachedCatalog() || {}).list;
    const mineCost = measured();
    const catalog = (Array.isArray(mineCat) && mineCat.length) ? mineCat
      : (Array.isArray(was.catalog) && was.catalog.length ? was.catalog : null);
    const costs = Object.keys(mineCost).length ? mineCost
      : (was.costs && Object.keys(was.costs).length ? was.costs : null);
    const oid = share ? (orgId() || (was.orgId || null)) : null;
    const oname = share ? ((org() && org().name) || was.orgName || '') : '';

    const changed = catalog !== was.catalog || costs !== was.costs ||
      oid !== (was.orgId || null) || oname !== (was.orgName || '');
    const block = {
      setUpBy: (t.email || was.setUpBy || ''),
      at: changed ? Date.now() : (was.at || Date.now()),
      orgId: oid,
      orgName: oname,
      catalog: catalog,
      costs: costs || {}
    };
    /* Nothing to hand anybody: leave the field off rather than writing an
     * empty block that every opener is then offered. */
    if (!block.orgId && !block.catalog && !Object.keys(block.costs).length) {
      p.settings.imagine = was.at ? was : null;
      SB.Store.touch();
      return p.settings.imagine;
    }
    p.settings.imagine = block;
    SB.Store.touch();
    return block;
  }

  /* Has this browser already been asked about this board's block? Keyed by
   * the stamp, so a board set up again asks again. */
  function askedKey(p) {
    const b = p && p.settings && p.settings.imagine;
    return b ? 'sb.imagine.asked.' + (p.id || '') + '.' + b.at : '';
  }

  function boardOffer(p) {
    const b = p && p.settings && p.settings.imagine;
    if (!b || !b.at) return null;
    if (lsStr(askedKey(p))) return null;
    /* nothing to offer if this browser already has all of it, or if the
     * board is carrying nothing worth taking */
    const sameOrg = !b.orgId || (orgId() === b.orgId);
    const hasCat = Array.isArray(b.catalog) && b.catalog.length;
    const hasCost = b.costs && Object.keys(b.costs).length;
    if (!b.orgId && !hasCat && !hasCost) return null;
    const haveCat = !!(cachedCatalog() || {}).list;
    const haveCost = Object.keys(measured()).length > 0;
    if (sameOrg && (haveCat || !hasCat) && (haveCost || !hasCost)) return null;
    return b;
  }

  function declineBoard(p) { lsPut(askedKey(p), '1'); }

  /* Take the board's settings for this browser. The organization is checked
   * against the account rather than assumed: a board can travel further than
   * the team that made it. */
  function adoptBoard(p) {
    const b = p && p.settings && p.settings.imagine;
    if (!b) return Promise.resolve(null);
    /* Everything learned is filed against the account it was learned for, so
     * adopting while signed out files it under "nobody" and it disappears
     * the moment somebody signs in. Ask again later instead of burning the
     * offer on a copy nobody will ever see. */
    if (transport() !== 'key' && !isSignedIn()) {
      return Promise.resolve({
        took: [],
        orgSkipped: 'sign in first — anything taken now would be filed against no account ' +
          'and lost the moment you did'
      });
    }
    lsPut(askedKey(p), '1');
    const took = [];
    if (Array.isArray(b.catalog) && b.catalog.length && !(cachedCatalog() || {}).list) {
      /* storeCatalog says whether it recognised a catalog at all — counting
         the thing we were handed used to report "10 models" for the string
         "not-a-list". */
      if (storeCatalog(b.catalog)) {
        took.push(((cachedCatalog() || {}).list || []).length + ' models');
      }
    }
    if (b.costs && Object.keys(b.costs).length) {
      const all = lsGet(K_COST) || {};
      const mine = all[catKey()] || {};
      Object.keys(b.costs).forEach(function (k) { if (!mine[k]) mine[k] = b.costs[k]; });
      all[catKey()] = mine;
      lsSet(K_COST, all);
      took.push(Object.keys(b.costs).length + ' measured prices');
    }
    if (!b.orgId || orgId() === b.orgId) {
      notify();
      return Promise.resolve({ took: took });
    }
    if (!isSignedIn()) {
      return Promise.resolve({ took: took, orgSkipped: 'sign in first, then set it in Settings' });
    }
    return listOrgs().then(function (list) {
      const hit = list.filter(function (o) { return o.id === b.orgId; })[0];
      if (!hit) {
        return { took: took, orgSkipped: 'your account is not a member of the organization ' +
          'this board was set up against' };
      }
      setOrg(hit);
      took.push('the organization (' + (hit.name || hit.id) + ')');
      return { took: took };
    }).catch(function () {
      return { took: took, orgSkipped: 'the organization could not be checked' };
    });
  }

  /* ---- the organisation ---- */

  function org() {
    const all = lsGet(K_ORG) || {};
    return all[catKey()] || null;
  }

  /* The tools want the id, not the record the picker stored. */
  function orgId() {
    const o = org();
    return (o && o.id) || '';
  }

  function setOrg(o) {
    const all = lsGet(K_ORG) || {};
    if (o) all[catKey()] = o; else delete all[catKey()];
    lsSet(K_ORG, all);
    notify();
  }

  /* select_organization renders a picker in a widget client and, in one like
   * this, hands back the list as text. Ids are uuids; names sit beside them. */
  function listOrgs() {
    return callRaw(TOOL.orgs, {}).then(function (got) {
      const text = got.text || JSON.stringify(got.raw || {});
      const out = [];
      const seen = {};
      const re = /([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})/gi;
      let m;
      while ((m = re.exec(text))) {
        const id = m[1];
        if (seen[id]) continue;
        seen[id] = 1;
        /* whatever reads like a name on the same line */
        const line = (text.slice(0, m.index).split('\n').pop() + text.slice(m.index).split('\n')[0]);
        const name = (line.replace(id, '').match(/[A-Za-z][\w .&'-]{1,40}/) || [''])[0].trim();
        out.push({ id: id, name: name || id.slice(0, 8) });
      }
      return out;
    });
  }

  /* ---- picking the tool for a job ----
   *
   * Scored rather than matched, because the names are ImagineArt's to change.
   * "text to image" and "generate_image" both have to win for image, and
   * neither must win for video.
   */
  const WANT = {
    image: { need: [/image|picture|photo/], plus: [/generat|create|text.?to.?image|txt2img/], minus: [/video|upscale|background|remove|music|audio|edit|lipsync|vector/] },
    video: { need: [/video|clip|animat/], plus: [/generat|create|text.?to.?video|image.?to.?video|i2v/], minus: [/upscale|extend|trim|lipsync|music|audio|frame|reframe/] },
    balance: { need: [/balance|credit/], plus: [/inquir|check|remaining/], minus: [] }
  };

  function score(tool, want) {
    const hay = ((tool.name || '') + ' ' + (tool.description || '')).toLowerCase();
    let s = 0;
    if (!want.need.some(function (re) { return re.test(hay); })) return -1;
    want.plus.forEach(function (re) { if (re.test(hay)) s += 2; });
    want.minus.forEach(function (re) { if (re.test(hay)) s -= 3; });
    /* A tool that takes an input image is the right one for image-to-video and
     * the wrong one for a plain still — decided by the caller, not here, so it
     * only breaks ties. */
    s += Math.max(0, 3 - (tool.name || '').length / 20);
    return s;
  }

  function pickTool(kind, opts) {
    return toolList().then(function (tools) {
      const want = WANT[kind];
      let best = null, bestScore = -1;
      tools.forEach(function (t) {
        let s = score(t, want);
        if (s < 0) return;
        if (opts && opts.needsImage) s += hasImageParam(t) ? 4 : -2;
        if (opts && opts.noImage && hasImageParam(t)) s -= 1;
        if (s > bestScore) { bestScore = s; best = t; }
      });
      if (!best) {
        throw new Error('The ImagineArt account exposes no ' + kind +
          ' tool — check Settings → ImagineArt for what it does offer.');
      }
      return best;
    });
  }

  function props(tool) {
    return (tool && tool.inputSchema && tool.inputSchema.properties) || {};
  }

  const IMAGE_PARAM = /^(image|image_url|image_uri|img|file|input_image|start_frame|first_frame|reference_image|init_image|source_image)$/i;

  function hasImageParam(tool) {
    return Object.keys(props(tool)).some(function (k) { return IMAGE_PARAM.test(k); });
  }

  /* ---- filling the arguments ----
   *
   * Canonical fields in, the tool's own property names out. Anything the
   * schema does not ask for is dropped rather than guessed at, and a required
   * enum with no value takes its first option so a call is not refused for
   * want of a field we have no opinion about.
   */
  const SYNONYM = {
    prompt: /^(prompt|text|description|input|query)$/i,
    slug: /^(model|style|model_name|model_id|engine|slug|variant)$/i,
    aspect: /^(aspect_ratio|aspectratio|ratio|aspect)$/i,
    duration: /^(duration|length|seconds|duration_seconds)$/i,
    image: IMAGE_PARAM,
    negative: /^(negative_prompt|negative)$/i
  };

  function bind(tool, canon) {
    const p = props(tool);
    const out = {};
    const used = {};
    Object.keys(canon).forEach(function (field) {
      const v = canon[field];
      if (v === undefined || v === null || v === '') return;
      const re = SYNONYM[field];
      if (!re) return;
      const hit = Object.keys(p).filter(function (k) { return re.test(k) && !used[k]; })[0];
      if (!hit) return;
      used[hit] = 1;
      const spec = p[hit] || {};
      /* An empty enum is not a list of allowed values, it is a schema saying
         nothing — treating it as one refused every model with a message that
         named no alternatives. */
      if (spec.enum && spec.enum.length && spec.enum.indexOf(v) < 0) {
        /* The account's own list is the truth. Something it does not offer is
         * the user's to fix, so say so rather than silently sending something
         * else — an aspect ratio quietly swapped for the first on the list is
         * a square frame where a widescreen one was asked for. */
        const offered = spec.enum.slice(0, 6).join(', ') + (spec.enum.length > 6 ? ', …' : '');
        if (field === 'slug') {
          throw new Error('“' + v + '” is not one of the models this account offers (' +
            offered + ').');
        }
        if (field === 'aspect') {
          throw new Error('This model does not offer ' + v + ' — it takes ' + offered +
            '. Change the aspect ratio in Settings → ImagineArt.');
        }
        return;
      }
      if (spec.type === 'number' || spec.type === 'integer') {
        const n = Number(v);
        /* Sending null for a duration is worse than not sending one. */
        if (!isFinite(n)) return;
        out[hit] = n;
      } else {
        out[hit] = v;
      }
    });
    ((tool.inputSchema && tool.inputSchema.required) || []).forEach(function (k) {
      if (out[k] !== undefined) return;
      const spec = p[k] || {};
      if (spec.default !== undefined) { out[k] = spec.default; return; }
      if (spec.enum && spec.enum.length) { out[k] = spec.enum[0]; return; }
    });
    return out;
  }

  /* A tool call by name with the arguments as published. The scored picker
   * below stays for anything unnamed, but every path this app uses now knows
   * exactly what it is calling. */
  function callRaw(name, args) {
    return mcpReady().then(function () {
      return mcpPost({
        jsonrpc: '2.0', id: ++mcp.id, method: 'tools/call',
        params: { name: name, arguments: args || {} }
      });
    }).then(function (r) {
      if (r && r.isError) throw new Error(harvest(r).text || 'ImagineArt refused the request.');
      return harvest(r);
    });
  }

  /* A generation comes back as a uuid and finishes later. sync:true waits
   * server-side for about 45 seconds, so this is a handful of long calls
   * rather than a busy loop — and it still gives up rather than hanging. */
  function waitForAsset(id, onState) {
    const started = Date.now();
    const look = function () {
      return callRaw(TOOL.status, { id: id, sync: true, org_id: orgId() }).then(function (got) {
        const blob = JSON.stringify((got.raw && got.raw.structuredContent) || {}) + ' ' + (got.text || '');
        const done = /"?status"?\s*[:=]\s*"?(complete|completed|success|finished)/i.test(blob);
        const failed = /"?status"?\s*[:=]\s*"?(error|failed)/i.test(blob);
        if (failed) afterSubmit(new Error(got.text ? got.text.slice(0, 200) : 'ImagineArt could not finish it.'));
        if (got.url && done) return got;
        if (got.url && !/queued|generating|processing|pending/i.test(blob)) return got;
        if (done) {
          /* Finished, and the file is not in the answer. Polling for ten
           * more minutes will not conjure one, and the caller must not treat
           * this as "the tools could not take it" — it was taken. */
          afterSubmit(new Error('ImagineArt finished it but sent no file back. It is on ' +
            'imagine.art under ' + id + '.'));
        }
        if (Date.now() - started > 10 * 60 * 1000) {
          afterSubmit(new Error('Gave up waiting after ten minutes. It may still finish on ' +
            'imagine.art — look there before spending another generation.'));
        }
        if (onState) onState('waiting', Date.now() - started);
        return wait(3000).then(look);
      });
    };
    return look();
  }

  /* A local picture has to become a URL before either generator will look at
   * it: the tools take image_url, never bytes. */
  function uploadForUrl(blob) {
    if (!blob) return Promise.resolve('');
    return blobToDataUrl(blob).then(function (data) {
      return callRaw(TOOL.upload, { file: data, org_id: orgId() });
    }).then(function (got) {
      if (!got.url) throw new Error('The upload came back without a URL.');
      return got.url;
    });
  }

  /* Both generators answer with a uuid and finish later. It arrives in the
   * structured content where there is any, and in the prose where there is
   * not. */
  function assetId(got) {
    const sc = (got && got.raw && got.raw.structuredContent) || null;
    const fromSc = sc && (sc.uuid || sc.id || (sc.data && (sc.data.uuid || sc.data.id)));
    if (fromSc && typeof fromSc === 'string') return fromSc;
    const m = /\b([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})\b/i
      .exec((got && got.text) || '');
    return m ? m[1] : '';
  }

  /* The allow-lists, the model lists and the tool names all live in the
   * descriptions, which only arrive with tools/list — and the generation
   * path only ever did `initialize`. So a session that opened a board and
   * pressed the button sent no resolution and no quality at all, which is
   * the model's floor: exactly what asking for a resolution was meant to
   * stop. Cached after the first call. */
  function ensureTools() {
    if (transport() === 'key' || !isSignedIn()) return Promise.resolve([]);
    if (mcp.tools) return Promise.resolve(mcp.tools);
    return toolList().catch(function () { return []; });
  }

  function needOrg() {
    if (org()) return '';
    return 'No ImagineArt organization chosen — every generation is billed to one. ' +
      'Settings → ImagineArt picks it.';
  }

  function callTool(kind, canon, opts) {
    return pickTool(kind, opts).then(function (tool) {
      const args = bind(tool, canon);
      return mcpPost({
        jsonrpc: '2.0', id: ++mcp.id, method: 'tools/call',
        params: { name: tool.name, arguments: args }
      }).then(function (r) {
        if (r && r.isError) {
          throw new Error(harvest(r).text || 'ImagineArt refused the request.');
        }
        const got = harvest(r);
        got.tool = tool.name;
        return got;
      });
    });
  }

  /* What came back: inline bytes, a URL, or text that mentions one. */
  function harvest(result) {
    const out = { dataUrl: '', url: '', text: '', raw: result };
    if (!result) return out;
    const content = result.content || [];
    content.forEach(function (c) {
      if (!c) return;
      if ((c.type === 'image' || c.type === 'audio' || c.type === 'video') && c.data) {
        if (!out.dataUrl) out.dataUrl = 'data:' + (c.mimeType || 'image/png') + ';base64,' + c.data;
      } else if (c.type === 'resource' && c.resource) {
        if (c.resource.blob && !out.dataUrl) {
          out.dataUrl = 'data:' + (c.resource.mimeType || 'application/octet-stream') +
            ';base64,' + c.resource.blob;
        }
        if (c.resource.uri && !out.url && /^https?:/.test(c.resource.uri)) out.url = c.resource.uri;
      } else if (c.type === 'resource_link' && c.uri) {
        if (!out.url && /^https?:/.test(c.uri)) out.url = c.uri;
      } else if (c.type === 'text' && c.text) {
        out.text += (out.text ? '\n' : '') + c.text;
      }
    });
    const sc = result.structuredContent;
    if (sc) {
      out.text = out.text || JSON.stringify(sc);
      deepUrl(sc, out);
    }
    if (!out.url && out.text) {
      const m = /(https?:\/\/[^\s")'<>]+)/.exec(out.text);
      if (m) out.url = m[1];
    }
    return out;
  }

  /* A structured reply can carry several URLs — the asset, and a docs or help
   * link beside it. Key order decided which one won, so an error payload
   * mentioning the documentation could be downloaded and filed as the clip.
   * The keys that mean "this is the thing" are preferred, and anything that
   * reads like documentation is taken last. */
  const ASSET_KEY = /^(url|uri|generation|output|result|video|image|asset|file|download|src|link)$/i;
  const DOCSY = /docs?\.|\/docs?\/|help|support|pricing|status\./i;

  function deepUrl(o, out, depth, key) {
    if (!o || (depth | 0) > 5) return;
    if (typeof o === 'string') {
      if (!/^https?:\/\//.test(o)) return;
      const rank = (ASSET_KEY.test(key || '') ? 2 : 0) + (DOCSY.test(o) ? -2 : 0);
      if (!out.url || rank > (out.urlRank | 0)) { out.url = o; out.urlRank = rank; }
      return;
    }
    if (typeof o !== 'object') return;
    Object.keys(o).forEach(function (k) { deepUrl(o[k], out, (depth | 0) + 1, k); });
  }

  /* An expiring CDN link does not fail — it answers 200 with an HTML page
   * saying so. Filing that as an mp4 loses the clip AND removes the warning
   * that would have told anyone to act, so what comes back is checked against
   * what was asked for. */
  function expectMedia(blob, kind) {
    const t = String((blob && blob.type) || '').toLowerCase();
    const ok = kind === 'video'
      ? /^video\//.test(t)
      : /^image\//.test(t);
    if (!blob || !blob.size) throw new Error('ImagineArt sent an empty file.');
    if (ok) return blob;
    /* No type at all is common and usually fine for a direct asset URL; an
     * actively wrong one (a web page, a JSON error) never is. */
    if (!t && blob.size > 1024) return blob;
    const e = new Error('That link did not give back ' +
      (kind === 'video' ? 'a clip' : 'a picture') +
      (t ? ' — it answered with ' + t : ' — it answered with nothing recognisable') +
      '. ImagineArt links expire; shoot it again.');
    e.wrongMedia = true;
    throw e;
  }

  /* ---------------- REST transport ---------------- */

  function apiKey() { return lsStr(K_KEY); }
  function setApiKey(v) { lsPut(K_KEY, (v || '').trim()); notify(); }

  function transport() {
    const m = lsStr(K_MODE);
    return m === 'key' ? 'key' : 'oauth';
  }
  function setTransport(id) { lsPut(K_MODE, id === 'key' ? 'key' : 'oauth'); notify(); }

  /* The bearer to use against api.vyro.ai, or nothing if that door is shut for
   * this session. The OAuth token is offered ONCE; whether it is accepted is
   * remembered so a refused token is not tried again on every press. */
  function restBearer() {
    if (transport() === 'key') {
      const k = apiKey();
      return k ? Promise.resolve(k) : Promise.reject(new Error('No ImagineArt API key — add one in Settings → ImagineArt.'));
    }
    if (lsStr(K_REST) === 'no') return Promise.resolve(null);
    return accessToken().then(function (t) { return t; });
  }

  function restFetch(path, init) {
    return restBearer().then(function (bearer) {
      if (!bearer) return null;
      const o = init || {};
      o.headers = o.headers || {};
      o.headers.Authorization = 'Bearer ' + bearer;
      return fetch(REST + path, o).then(function (res) {
        /* A signed-in session learns here, once, whether its token is good for
         * the REST API at all. */
        if (transport() === 'oauth') {
          if (res.status === 401 || res.status === 403) {
            lsPut(K_REST, 'no');
            return null;
          }
          if (lsStr(K_REST) !== 'yes') lsPut(K_REST, 'yes');
        }
        return res;
      });
    });
  }

  function restImage(canon) {
    const fd = new FormData();
    fd.append('prompt', canon.prompt);
    fd.append('style', canon.slug);
    if (canon.aspect) fd.append('aspect_ratio', canon.aspect);
    return restFetch('/image/generations', { method: 'POST', body: fd }).then(function (res) {
      if (!res) return null;
      const ct = res.headers.get('content-type') || '';
      if (res.ok && ct.indexOf('application/json') < 0) {
        return res.blob().then(function (b) { return { blob: b }; });
      }
      return jsonOrText(res).then(function (p) {
        /* Some models answer asynchronously even here. */
        if (res.ok && p.body && p.body.id) return pollAsset(p.body.id, canon.onState);
        throw apiError(res, p);
      });
    });
  }

  function restVideo(canon) {
    const fd = new FormData();
    fd.append('prompt', canon.prompt);
    fd.append('style', canon.slug);
    if (canon.aspect) fd.append('aspect_ratio', canon.aspect);
    const path = canon.frame ? '/video/image-to-video' : '/video/text-to-video';
    if (canon.frame) fd.append('file', canon.frame, canon.frameName || 'frame.png');
    return restFetch(path, { method: 'POST', body: fd }).then(function (res) {
      if (!res) return null;
      return jsonOrText(res).then(function (p) {
        if (!res.ok || !p.body || !p.body.id) throw apiError(res, p);
        return pollAsset(p.body.id, canon.onState);
      });
    });
  }

  /* Video is minutes, not seconds. Back off from 2s to 10s, give up at ten
   * minutes, and report each look so a row can show that it is still alive. */
  function pollAsset(id, onState) {
    const started = Date.now();
    let gap = 2000;
    const look = function () {
      return restFetch('/assets/' + encodeURIComponent(id) + '/status', { method: 'GET' })
        .then(function (res) {
          if (!res) throw new Error('ImagineArt stopped accepting the session mid-job.');
          return jsonOrText(res).then(function (p) {
            if (!res.ok) throw apiError(res, p);
            const body = p.body || {};
            const asset = body.video || body.image || body.asset || body;
            const st = String(asset.status || body.status || '').toLowerCase();
            const url = (asset.url && (asset.url.generation || asset.url.output)) ||
              asset.url || '';
            if (url && (st === 'finished' || st === 'success' || st === 'completed')) {
              return {
                url: typeof url === 'string' ? url : '',
                thumb: (asset.url && asset.url.thumbnail) || ''
              };
            }
            if (st === 'failed' || st === 'error') {
              throw new Error(asset.message || body.message || 'ImagineArt could not finish that one.');
            }
            if (Date.now() - started > 10 * 60 * 1000) {
              throw new Error('Gave up waiting after ten minutes. The job may still finish on imagine.art.');
            }
            if (onState) onState('waiting', Date.now() - started);
            return wait(gap).then(function () {
              gap = Math.min(10000, Math.round(gap * 1.4));
              return look();
            });
          });
        });
    };
    return look();
  }

  /* ---------------- the two things the app asks for ---------------- */

  function aspectOf(p) {
    return (p && p.settings && p.settings.imagineAspect) || '16:9';
  }

  /* The name this door knows the model by, falling back to the other one —
   * a single name is better than none, and an unrecognised one is flagged
   * rather than refused. */
  function slugOf(model, forTransport) {
    if (!model) return '';
    const mcp = (model.imagineSlug || '').trim();
    const rest = (model.restSlug || '').trim();
    const door = forTransport || transport();
    return door === 'key' ? (rest || mcp) : (mcp || rest);
  }

  /* Why a push cannot happen yet, or '' if it can. Said in one place so the
   * button's tooltip and the Settings panel never disagree. */
  function blocker(model) {
    if (transport() === 'key') {
      if (!apiKey()) return 'No ImagineArt API key — Settings → ImagineArt.';
    } else if (!isSignedIn()) {
      return 'Not signed in to ImagineArt — Settings → ImagineArt.';
    } else if (!org()) {
      /* Caught here rather than at the press: every generation is billed to
       * an organization, so without one the button cannot work and should
       * not look as though it can. */
      return 'No ImagineArt organization chosen — Settings → ImagineArt.';
    }
    if (!slugOf(model)) {
      return 'This model has no ImagineArt model set — Settings → Models & templates.';
    }
    return '';
  }

  /* ---------------- which door ----------------
   *
   * Signing in is a choice of surface, not just of billing: the MCP server is
   * ImagineArt's current product and the v2 REST API is an older, smaller one
   * — six image models against the twenty-two the website offers, and a
   * newest Kling of 1.6 against 2.6. A signed-in session that quietly went
   * through REST because the token happened to be accepted there was
   * answering a question the user thought they had already answered.
   *
   * So: signed in means MCP first. REST is the fallback, for the one thing it
   * is definitely better at — it takes an uploaded frame — and for whatever
   * the account's tools turn out not to do. The API-key transport has only
   * ever had REST.
   *
   * Which door actually carried the last generation is recorded, because with
   * a fallback in play "where did this come from" stops being obvious.
   */
  function door() { return lsStr(K_DOOR); }
  function noteDoor(d) { lsPut(K_DOOR, d); }

  /* The fallback exists for one case: the account's tools could not take the
   * job at all. It must never run after a generation has been SUBMITTED —
   * that is a second one, and it is billed. A job that was accepted and then
   * failed, timed out, or came back without a file has already cost money,
   * and the honest answer is the failure.
   *
   * Anything thrown after submission carries `submitted`; an auth failure
   * carries `auth`. Both stop here. */
  function firstOf(primary, fallback) {
    return primary().then(function (r) {
      if (r) return r;
      return fallback();
    }, function (e) {
      if (e && (e.auth || e.submitted)) throw e;
      return fallback().catch(function () { throw e; });
    });
  }

  function afterSubmit(e) {
    const err = (e instanceof Error) ? e : new Error(String(e));
    err.submitted = true;
    throw err;
  }

  /* One still. Resolves to {blob, dataUrl}. */
  function image(opts) {
    const canon = {
      prompt: opts.prompt, slug: opts.slug, restSlug: opts.restSlug || '',
      aspect: opts.aspect, resolution: opts.resolution || '', quality: opts.quality || '',
      onState: opts.onState
    };
    const viaMcp = function () {
      const why = needOrg();
      if (why) return Promise.reject(new Error(why));
      /* A reference is a URL, never bytes, and ours are local -- so it is
       * uploaded first, exactly as the video door already does with its frame.
       *
       * If that upload fails the push does NOT quietly carry on without it.
       * Falling through to a door that cannot carry a reference at all would
       * render the prompt's "keep their face exactly as in that image" against
       * no image, which is the whole bug this is here to fix -- so the failure
       * is marked as final and says what it was. */
      return (opts.refBlob ? uploadForUrl(opts.refBlob) : Promise.resolve(''))
        .catch(function (e) {
          const err = new Error('The reference picture could not be uploaded, so the ' +
            'still was not made: ' + (e.message || e) + '. Nothing was charged.');
          err.submitted = true;
          throw err;
        })
        .then(function (refUrl) {
          /* aspect_ratio, model and duration are required-but-nullable on this
           * tool, so the keys travel even when there is nothing to put in them. */
          const args = {
            org_id: orgId(),
            prompt: canon.prompt,
            model: canon.slug || null,
            aspect_ratio: canon.aspect || null,
            duration: null,
            image_url: refUrl || opts.imageUrl || null
          };
          if (canon.resolution) args.resolution = canon.resolution;
          if (canon.quality) args.quality = canon.quality;
          /* Everything inside this `then` happens after ImagineArt accepted
           * the job, so every failure in it is a failure of a generation that
           * has already cost something — never a reason to try the other
           * door. A rejection from callRaw itself is the tools refusing the
           * job, which is the one case the fallback is for. */
          return callRaw(TOOL.image, args).then(function (got) {
            const id = assetId(got);
            const settled = (got.url && !id)
              ? Promise.resolve(got) : waitForAsset(id || got.text, canon.onState);
            return settled.then(function (g2) {
              noteDoor('mcp');
              return finishImage(g2);
            }).then(function (out) {
              out.usedSlug = canon.slug || '';
              out.via = 'mcp';
              return out;
            }).catch(afterSubmit);
          });
        });
    };
    const viaRest = function () {
      /* The v2 API knows this model by a different name, and the board
       * carries both — sending the account's name here is a wasted round
       * trip at best and a silent wrong model at worst. */
      const restCanon = Object.assign({}, canon, { slug: canon.restSlug || canon.slug });
      if (!restCanon.slug) return Promise.resolve(null);
      return restImage(restCanon).then(function (got) {
        if (!got) return null;
        noteDoor('rest');
        return finishImage(got).then(function (out) {
          out.usedSlug = restCanon.slug;
          out.via = 'rest';
          return out;
        });
      });
    };
    if (transport() === 'key') {
      return viaRest().then(function (r) {
        if (!r) throw new Error('ImagineArt did not answer with a picture.');
        return r;
      });
    }
    return firstOf(viaMcp, function () {
      return viaRest().then(function (r) {
        if (!r) throw new Error('Neither your account\u2019s tools nor the REST API made that ' +
          'picture. Settings → ImagineArt → what my account can do says what it offers.');
        return r;
      });
    });
  }

  function finishImage(got) {
    if (got.blob) {
      return blobToDataUrl(got.blob).then(function (d) { return { blob: got.blob, dataUrl: d }; });
    }
    if (got.dataUrl) {
      return dataUrlToBlob(got.dataUrl).then(function (b) {
        return { blob: b, dataUrl: got.dataUrl };
      });
    }
    if (got.url) {
      /* The CDN may or may not allow a cross-origin read. If it does we get the
       * original bytes; if it does not, the URL is still worth handing back. */
      return fetch(got.url).then(function (r) {
        if (!r.ok) throw new Error('HTTP ' + r.status);
        return r.blob();
      }).then(function (b) {
        return expectMedia(b, 'image');
      }).then(function (b) {
        return blobToDataUrl(b).then(function (d) { return { blob: b, dataUrl: d, url: got.url }; });
      }).catch(function () {
        return { blob: null, dataUrl: '', url: got.url };
      });
    }
    throw new Error('ImagineArt answered without a picture' + (got.text ? ': ' + got.text.slice(0, 160) : '.'));
  }

  /* One clip. `frame` is a Blob to animate from, or nothing for text-to-video.
   * Resolves to {blob, url, thumb} — blob may be null if the CDN refuses a
   * cross-origin read, and the URL is then all there is. */
  function video(opts) {
    const canon = {
      prompt: opts.prompt, slug: opts.slug, restSlug: opts.restSlug || '',
      aspect: opts.aspect,
      duration: opts.duration, resolution: opts.resolution || '',
      frame: opts.frame, frameName: opts.frameName,
      onState: opts.onState
    };
    const viaMcp = function () {
      const why = needOrg();
      if (why) return Promise.reject(new Error(why));
      /* One image means "animate this still"; two or more would mean
       * reference-to-video, which only some models take. The frame is local,
       * so it has to become a URL first. */
      return (opts.frame ? uploadForUrl(opts.frame) : Promise.resolve(''))
        .then(function (url) {
          const args = {
            org_id: orgId(),
            prompt: canon.prompt,
            model: canon.slug || null,
            aspect_ratio: canon.aspect || null,
            duration: canon.duration ? String(canon.duration) : null,
            image_url: url ? [url] : null
          };
          if (canon.resolution) args.resolution = canon.resolution;
          return callRaw(TOOL.video, args);
        })
        .then(function (got) {
          const id = assetId(got);
          const settled = (got.url && !id)
            ? Promise.resolve(got) : waitForAsset(id || got.text, canon.onState);
          return settled.then(function (g2) {
            noteDoor('mcp');
            return finishVideo(g2);
          }).then(function (out) {
            out.usedSlug = canon.slug || '';
            out.via = 'mcp';
            return out;
          }).catch(afterSubmit);
        });
    };
    const viaRest = function () {
      const restCanon = Object.assign({}, canon, { slug: canon.restSlug || canon.slug });
      if (!restCanon.slug) return Promise.resolve(null);
      return restVideo(restCanon).then(function (got) {
        if (!got) return null;
        noteDoor('rest');
        return finishVideo(got).then(function (out) {
          out.usedSlug = restCanon.slug;
          out.via = 'rest';
          return out;
        });
      });
    };
    if (transport() === 'key') {
      return viaRest().then(function (r) {
        if (!r) throw new Error('ImagineArt did not answer with a clip.');
        return r;
      });
    }
    return firstOf(viaMcp, function () {
      return viaRest().then(function (r) {
        if (!r) throw new Error('Neither your account\u2019s tools nor the REST API made that ' +
          'clip. Settings → ImagineArt → what my account can do says what it offers.');
        return r;
      });
    });
  }

  function finishVideo(got) {
    const url = got.url || '';
    if (got.blob) return Promise.resolve({ blob: got.blob, url: url, thumb: got.thumb || '' });
    if (got.dataUrl) {
      return dataUrlToBlob(got.dataUrl).then(function (b) {
        return { blob: b, url: url, thumb: got.thumb || '' };
      });
    }
    if (!url) {
      throw new Error('ImagineArt answered without a clip' + (got.text ? ': ' + got.text.slice(0, 160) : '.'));
    }
    return fetch(url).then(function (r) {
      if (!r.ok) throw new Error('HTTP ' + r.status);
      return r.blob();
    }).then(function (b) {
      return { blob: expectMedia(b, 'video'), url: url, thumb: got.thumb || '' };
    }).catch(function () {
      /* No bytes: the link is all there is, and the board says so rather than
       * filing whatever came back. */
      return { blob: null, url: url, thumb: got.thumb || '' };
    });
  }

  /* ---------------- jobs ----------------
   *
   * A clip takes minutes and the prompt table re-renders on every keystroke,
   * so what is in flight cannot live on a DOM node. It lives here, keyed by
   * shot and role, and the table reads it. Closing the panel mid-job and
   * opening it again finds the job exactly where it was.
   */
  const JOBS = {};
  const LISTENERS = [];

  function key(shotId, role) { return shotId + ':' + role; }

  function job(shotId, role) { return JOBS[key(shotId, role)] || null; }
  function runningJobs() {
    return Object.keys(JOBS).filter(function (k) {
      const j = JOBS[k];
      return j && (j.state === 'working' || j.state === 'waiting');
    }).length;
  }

  function busy(shotId, role) {
    const j = job(shotId, role);
    return !!(j && (j.state === 'working' || j.state === 'waiting'));
  }

  function onChange(fn) {
    LISTENERS.push(fn);
    return function () {
      const i = LISTENERS.indexOf(fn);
      if (i >= 0) LISTENERS.splice(i, 1);
    };
  }

  let pending = null;
  function notify() {
    /* Several fields move at once at the start and end of a job; one repaint
     * covers them. */
    if (pending) return;
    pending = setTimeout(function () {
      pending = null;
      LISTENERS.slice().forEach(function (fn) {
        try { fn(); } catch (e) { }
      });
    }, 0);
  }

  function start(shotId, role) {
    const j = { shotId: shotId, role: role, state: 'working', started: Date.now(), error: '' };
    JOBS[key(shotId, role)] = j;
    notify();
    return j;
  }

  function endJob(shotId, role, error) {
    const k = key(shotId, role);
    const j = JOBS[k];
    if (!j) return;
    if (error) {
      j.state = 'error';
      j.error = error.message || String(error);
      j.ended = Date.now();
      /* An error stays on the row until the next press — it is the only place
       * the reason is written down. */
    } else {
      delete JOBS[k];
    }
    notify();
  }

  /* Clearing is for the error a row is still showing, not for a generation
   * that is in the air: dropping the record would take the guard off and let
   * a second one start — two clips, two charges, one shot. A running job ends
   * when it ends. */
  function clear(shotId, role) {
    if (busy(shotId, role)) return false;
    delete JOBS[key(shotId, role)];
    notify();
    return true;
  }

  /* ---------------- run one ----------------
   *
   * The single entry point the prompt table uses: one press, one generation,
   * results filed where the rest of the app already looks for them.
   */
  function run(shot, role) {
    const p = SB.app.project;
    if (busy(shot.id, role)) return Promise.resolve(null);

    const model = role === 'image' ? SB.Model.imageModel(p) : SB.Model.videoModel(p);
    const why = blocker(model);
    if (why) return Promise.reject(new Error(why));

    /* The button refuses one of these too, but run() is the public door and
     * has to hold the same line on its own. */
    if (shot.noShot) {
      return Promise.reject(new Error('A “no shot” card is never generated.'));
    }

    const pr = shot.prompts && shot.prompts[model.id];
    const text = pr && (role === 'image' ? pr.imagePrompt : pr.videoPrompt);
    if (!(text || '').trim()) {
      return Promise.reject(new Error('There is no ' +
        (role === 'image' ? 'first-frame' : 'video') + ' prompt on this shot yet.'));
    }

    /* An image-to-video model with no frame, or a text-to-video one with a
     * frame in hand, is a wasted generation — and on this platform the two
     * are different slugs, not a flag. Caught before the credits go. */
    /* Only the v2 REST API splits a model into a text-to-video slug and an
     * image-to-video one. The account's tools take one model and decide from
     * whether an image came with it, so this check is about the REST
     * transport and would be nonsense on the other. */
    if (role === 'video' && transport() === 'key') {
      const info = modelInfo(slugOf(model));
      const has = !!(shot.render || shot.image);
      if (info && info.mode === 't2v' && has) {
        return Promise.reject(new Error('“' + slugOf(model) + '” is a text-to-video model, and ' +
          'this shot has a frame to animate. Point this model at the matching ' +
          'image-to-video slug in Settings → Models & templates.'));
      }
      if (info && info.mode === 'i2v' && !has) {
        return Promise.reject(new Error('“' + slugOf(model) + '” animates a picture, and this ' +
          'shot has none yet. Render the first frame, or use the text-to-video slug.'));
      }
    }

    /* The allow-lists and the model names live in the tool descriptions, so
     * nothing below is knowable until the tools have been read. */
    return ensureTools().then(function () {
      const aspect = aspectOf(p);
      const slugNow = slugOf(model);
      const allowed = transport() === 'key'
        ? null : allowFor(role === 'image' ? TOOL.image : TOOL.video, slugNow, 'aspect_ratio');
      if (allowed && allowed.length && allowed.indexOf(aspect) < 0) {
        /* The tool takes an unlisted ratio and silently makes 16:9 of it, so
         * four of the six shapes on the board's list were paid-for lies. */
        return Promise.reject(new Error('“' + slugNow + '” does not offer ' + aspect +
          ' — it takes ' + allowed.join(', ') + '. Change the aspect ratio in ' +
          'Settings → ImagineArt, or point this model somewhere that offers it.'));
      }

      const j = start(shot.id, role);
      const state = function (s2) { j.state = s2; notify(); };

      /* Stamped onto whatever comes back, because an export that can say
       * "these eleven were generated, off these prompts, by this model" is a
       * different thing from one that hands over a folder of pictures. The
       * slug and the door are filled in from what actually carried it. */
      const made = {
        by: 'imagine', role: role, model: model.name, modelId: model.id,
        slug: slugNow, via: transport(), at: Date.now()
      };
      const frameRef = (shot.image && shot.image.ref) || '';

      /* Ids, not objects. Everything this generation needs to find its way
         home is looked up again when it arrives — see land(). */
      const ticket = {
        projectId: p.id, projectName: p.name || '', shotId: shot.id,
        code: codeOf(p, shot) || '', role: role, frameRef: frameRef, made: made
      };

      const res = resolutionFor(p, slugNow, role);
      const qual = role === 'image' ? qualityFor(p, slugNow) : '';
      made.resolution = res || '';

      /* A measurement is only worth anything if this generation is the only
       * one in the air: two at once and the difference is both of them. */
      const alone = runningJobs() === 1;
      const before = alone ? balanceNow() : Promise.resolve(null);

      const work = role === 'image'
        ? before.then(function () { return firstRef(p, shot); }).then(function (ref) {
          made.reference = ref ? { label: ref.label, n: ref.n, of: ref.of } : null;
          return image({
            prompt: text, slug: slugNow, restSlug: slugOf(model, 'key'),
            aspect: aspect, resolution: res, quality: qual,
            refBlob: ref && ref.blob,
            onState: function () { state('waiting'); }
          });
        }).then(function (got) {
          made.slug = got.usedSlug || made.slug;
          made.via = got.via || made.via;
          return land(ticket, got).then(function (out) {
            out.usedSlug = got.usedSlug;
            return out;
          });
        })
        : before.then(function () { return startFrame(p, shot); }).then(function (frame) {
          return video({
            prompt: text, slug: slugNow, restSlug: slugOf(model, 'key'),
            aspect: aspect, resolution: res,
            frame: frame && frame.blob, frameName: frame && frame.name,
            onState: function () { state('waiting'); }
          });
        }).then(function (got) {
          made.slug = got.usedSlug || made.slug;
          made.via = got.via || made.via;
          return land(ticket, got).then(function (out) {
            out.usedSlug = got.usedSlug;
            return out;
          });
        });

      return work.then(function (out) {
        endJob(shot.id, role);
        const used = (out && out.usedSlug) || made.slug;
        noteWorked(used, role === 'image' ? 'image' : 'video');
        model.lastUsed = { slug: used, via: made.via, at: Date.now() };
        SB.Store.touch();
        /* What it actually cost, from the two balances — only when this was
         * the only job running at both ends, or the difference is somebody
         * else's generation too. */
        if (alone) {
          before.then(function (was) {
            if (!(was > 0) || runningJobs() !== 0) return null;
            return balanceNow().then(function (now) {
              if (!(now > 0)) return null;
              const spent = Math.round((was - now) * 100) / 100;
              if (spent > 0) noteCost(used, '', res, spent);
              return null;
            });
          }).catch(function () { });
        }
        return out;
      }).catch(function (e) {
        endJob(shot.id, role, e);
        throw e;
      });
    });
  }


  /* The frame a clip animates from: the full-size original the board is
   * carrying, its ≤480p proxy if the original predates them being kept in the
   * file, and nothing at all if the shot has no picture — which is a
   * text-to-video, not a failure. */
  /* The reference picture a STILL push can carry.
   *
   * It could not carry one at all until now. generate_image was called with
   * prompt, model and aspect and nothing else, while the prompt it carried
   * said "Reference images are supplied in order -- refer to each recurring
   * subject as the person in image 1, and keep their face, hair and wardrobe
   * exactly as in that image". Nothing was supplied. The model was told about
   * pictures it had never been given and did the only thing left to it, which
   * is invent an image 1 and call it whoever the words named. That is worse
   * than sending nothing and saying nothing: the mapping reads as authority.
   *
   * The door takes ONE (generate_image takes a single image_url; only
   * generate_video takes an array), so it carries the first in feed order --
   * which is the one the prompt's own mapping calls image 1, so the words and
   * the picture finally agree. Everything after it stays described in words,
   * and the panel says how many those are rather than leaving it to be
   * discovered in the result.
   *
   * The original where the board has one, the proxy where it does not: a
   * reference is there to be matched, and 480p is a poor thing to match. */
  function firstRef(p, shot) {
    /* the still's own lane: the picture a first frame is matched against */
    const feed = SB.Refs.images(p, shot, 'image');
    const e = feed[0];
    if (!e) return Promise.resolve(null);
    const name = 'ref1-' + (SB.Renders.slug(e.label) || 'ref') + '.png';
    return SB.Renders.file(p, e.render).then(function (f) {
      if (f) return { blob: f, name: f.name || name, label: e.label, n: e.n, of: feed.length };
      const src = e.img ? SB.Blobs.src(p, e.img) : '';
      if (!src) return null;
      return dataUrlToBlob(src).then(function (b) {
        return { blob: b, name: name, label: e.label, n: e.n, of: feed.length };
      });
    }).catch(function () { return null; });
  }

  function startFrame(p, shot) {
    return SB.Renders.file(p, shot.render).then(function (f) {
      if (f) return { blob: f, name: f.name };
      const src = shot.image ? SB.Blobs.src(p, shot.image) : '';
      if (!src) return null;
      return dataUrlToBlob(src).then(function (b) { return { blob: b, name: 'frame.jpg' }; });
    }).catch(function () { return null; });
  }

  /* A generated still is filed exactly like a dropped one — proxy on the
   * board, original in the file under its serial. Which is the point: the
   * next shot can reference it ten seconds later, and so can whoever the
   * board is handed to. */
  function fileImage(p, shot, got, made) {
    if (!got.blob) {
      throw new Error('ImagineArt made the picture but this browser could not read it back' +
        (got.url ? ' — it is at ' + got.url : '.'));
    }
    return SB.Board.setImage(shot, got.blob, made).then(function () {
      return { kind: 'image' };
    });
  }

  /* Minutes pass between asking for a clip and filing it, which is plenty of
   * time for two cards to be swapped. A clip belongs to the frame it was
   * animated from, so it is filed against that picture rather than against
   * the card that asked. */
  /* ---------------- landing a generation ----------------
   *
   * A generation takes minutes, and run() used to close over the project and
   * the shot OBJECT it was started from. Both of those can stop being the
   * board you are looking at while it is in the air:
   *
   *   Open… / New          swaps SB.app.project outright
   *   restoring a version  replaces p.scenes with cloned snapshot scenes, so
   *                        the shot object is no longer the shot in the board
   *   deleting the card    takes it out of every scene
   *
   * In every one of those, the clip landed perfectly — onto an object nothing
   * points at. Then Store.touch() fired, and writeNow() asked S.getProject()
   * for the board to write, which was the NEW one. So the file on disk was
   * rewritten without the clip, the clip lived in the memory of an
   * unreferenced object, and reopening the board it belonged to did not have
   * it. Minutes of generation and the credits, gone with no error.
   *
   * So nothing is captured but ids, and the board is looked up again at the
   * moment the bytes arrive. If it is not the one on screen, the result is
   * PARKED rather than filed, and filed when that board is opened again. */
  const PARKED = [];

  function parkedFor(projectId) {
    return PARKED.filter(function (x) { return x.projectId === projectId; });
  }
  function parkedCount() { return PARKED.length; }

  /* Somebody opened a board. Anything waiting for it is filed now. */
  function claimParked(p) {
    if (!p || !p.id) return 0;
    const mine = parkedFor(p.id);
    if (!mine.length) return 0;
    mine.forEach(function (x) {
      const i = PARKED.indexOf(x);
      if (i >= 0) PARKED.splice(i, 1);
    });
    let filed = 0, lost = 0;
    const step = function (i) {
      if (i >= mine.length) {
        if (filed) {
          SB.toast(filed === 1 ? 'The clip that finished while this board was closed is on it now'
            : filed + ' generations that finished while this board was closed are on it now');
        }
        if (lost) SB.toast(lost + ' could not be filed — the card is gone', true);
        notify();
        return;
      }
      const x = mine[i];
      const f = SB.Model.findShot(p, x.shotId);
      if (!f) { lost++; return step(i + 1); }
      const done = function () { filed++; step(i + 1); };
      const fail = function (e) {
        lost++;
        console.error('[storyboarder] a parked generation could not be filed', e);
        step(i + 1);
      };
      if (x.role === 'image') fileImage(p, f.shot, x.got, x.made).then(done).catch(fail);
      else fileVideo(p, targetFor(p, f.shot, x.frameRef), x.got, x.made).then(done).catch(fail);
    };
    step(0);
    return mine.length;
  }

  /* The board this was started on, if it is still the board on screen. */
  function boardIfOpen(projectId) {
    const cur = SB.app && SB.app.project;
    return (cur && cur.id === projectId) ? cur : null;
  }

  function land(ticket, got) {
    const p = boardIfOpen(ticket.projectId);
    const f = p ? SB.Model.findShot(p, ticket.shotId) : null;
    /* Parking is for a board that is not open, because opening it is what
       claims the result. A card deleted out of the board you are LOOKING at
       has no such moment coming: parked, it sat in the list forever, holding
       the toolbar count up and warning on every close, promising a recovery
       that could not happen. There is nowhere to put it, so say that. */
    if (p && !f) {
      SB.toast('The ' + (ticket.role === 'image' ? 'frame' : 'clip') + ' for ' +
        (ticket.code || 'a card') + ' finished, but that card is not on the board ' +
        'any more \u2014 so there is nowhere to put it.', true);
      notify();
      return Promise.resolve({ kind: ticket.role, dropped: true });
    }
    if (!p || !f) {
      PARKED.push({
        projectId: ticket.projectId, projectName: ticket.projectName,
        shotId: ticket.shotId, code: ticket.code, role: ticket.role,
        frameRef: ticket.frameRef, got: got, made: ticket.made, at: Date.now()
      });
      notify();
      SB.toast('The ' + (ticket.role === 'image' ? 'frame' : 'clip') + ' for ' +
        (ticket.code || 'a card') + ' finished, but ' +
        (p ? 'that card is no longer on the board'
           : '“' + (ticket.projectName || 'the board it belongs to') + '” is not open') +
        '. It is held' + (p ? '' : ' — open that board again and it will be filed') +
        '. Closing this tab loses it.', true);
      return Promise.resolve({ kind: ticket.role, parked: true });
    }
    return ticket.role === 'image'
      ? fileImage(p, f.shot, got, ticket.made)
      : fileVideo(p, targetFor(p, f.shot, ticket.frameRef), got, ticket.made);
  }

  function targetFor(p, shot, frameRef) {
    if (!frameRef) return shot;
    if (shot.image && shot.image.ref === frameRef) return shot;
    return SB.Model.shotHolding(p, frameRef) || shot;
  }

  function fileVideo(p, shot, got, made) {
    /* Shooting again is what you do when the clip is mostly right, so the one
     * on the card is kept rather than overwritten. The new one becomes the
     * chosen take -- trying again is an attempt to do better -- and the old
     * one is a click away in the clip window. The swap happens at the bottom
     * of this function, in one step, once there is something to swap IN. */
    /* unseen: nobody has watched this one yet. Shooting a dozen clips means
     * going away and coming back to a board where every row looks the same,
     * with no way to tell the one that just landed from the one watched ten
     * minutes ago — so a clip arrives marked, and watching it unmarks it.
     * Only clips made HERE: a file somebody dropped in was chosen by hand and
     * has already been seen. */
    const rec = { at: Date.now(), url: got.url || '', thumb: got.thumb || '',
      made: made || null, unseen: true };
    if (!got.blob) {
      /* ImagineArt made it but the browser could not read the bytes back
       * across origins: hold the link, say so, and leave a way to try again
       * while the link is still alive. */
      SB.Model.addTake(shot, rec);
      SB.Focus.defer('clip:' + shot.id, function () { SB.app.changed(true); });
      return Promise.resolve({ kind: 'video', remoteOnly: true });
    }
    return SB.Renders.keepVideo(p, got.blob, shot.video, made).then(function (saved) {
      /* The whole record, ref included. Rebuilding it field by field dropped
       * the ref once, which put the bytes in the file with nothing pointing at
       * them — so the clip played until the next structural change swept it
       * away, and then the board had a link and no clip. */
      if (saved) {
        saved.url = rec.url;
        saved.thumb = rec.thumb;
        saved.unseen = true;
      }
      SB.Model.addTake(shot, saved || rec);
      /* Minutes after the button was pressed. Whoever pressed it is writing
         something else by now, and rebuilding the board under them is how a
         half-typed prompt used to disappear. */
      SB.Focus.defer('clip:' + shot.id, function () { SB.app.changed(true); });
      return { kind: 'video', remoteOnly: !saved };
    });
  }

  /* A second chance at a clip whose bytes never arrived. The link ImagineArt
   * hands back works for a while and then does not, so this is worth reaching
   * for the moment the board says "link only" rather than later. */
  function fetchClip(shot) {
    const p = SB.app.project;
    const rec = shot && shot.video;
    if (!rec || rec.ref) return Promise.resolve(false);
    if (!rec.url) return Promise.reject(new Error('That clip has no link left to fetch from.'));
    return fetch(rec.url).then(function (r) {
      if (!r.ok) throw new Error('ImagineArt answered ' + r.status);
      return r.blob();
    }).then(function (b) {
      return SB.Renders.keepVideo(p, expectMedia(b, 'video'), rec, rec.made);
    }).then(function (saved) {
      if (!saved) throw new Error('the clip could not be stored');
      saved.url = rec.url;
      saved.thumb = rec.thumb;
      /* fetching the bytes is not watching the clip */
      if (rec.unseen) saved.unseen = true;
      shot.video = saved;
      SB.Focus.defer('clip:' + shot.id, function () { SB.app.changed(true); });
      return true;
    });
  }

  /* ---------------- what Settings shows ---------------- */

  /* What the account itself advertises. Read per tool, so the kind comes from
   * the tool the enum was on rather than from guessing at the slug's spelling
   * — which is how "wan" ended up classified by a regex of model names I
   * happened to think of. */
  /* What the account's own tools say they take.
   *
   * ImagineArt publishes its model lists in prose inside the tool
   * description rather than as a JSON enum, so they are parsed from there —
   * and the first one listed is the default that tool uses. Nothing here is
   * a guess about spelling: the kind comes from which tool the list was on.
   *
   * An enum is still read where a tool has one, for any server that does it
   * the ordinary way. */
  function fromAccount() {
    const out = [];
    const seen = {};
    const take = function (slug, kind, extra) {
      if (typeof slug !== 'string' || !slug || seen[slug]) return;
      seen[slug] = 1;
      out.push(Object.assign({ slug: slug, kind: kind, from: 'account' }, extra || {}));
    };
    modelsFromTool(TOOL.image).forEach(function (m, i) {
      take(m, 'image', { deflt: i === 0 });
    });
    modelsFromTool(TOOL.video).forEach(function (m, i) {
      take(m, 'video', { deflt: i === 0 });
    });
    (mcp.tools || []).forEach(function (t) {
      if (t.name === TOOL.image || t.name === TOOL.video) return;
      const kind = score(t, WANT.video) > score(t, WANT.image) ? 'video' : 'image';
      const ps = props(t);
      Object.keys(ps).forEach(function (k) {
        if (!SYNONYM.slug.test(k)) return;
        (ps[k].enum || []).forEach(function (v) { take(v, kind); });
      });
    });
    return out;
  }

  function catKey() {
    const t = tokens();
    return (transport() === 'key' ? 'key' : ((t && t.email) || 'signed-in'));
  }

  function cachedCatalog() {
    const all = lsGet(K_CAT) || {};
    return all[catKey()] || null;
  }

  function cleanCatalog(list) {
    if (!Array.isArray(list)) return null;
    const out = list.filter(function (m) {
      return m && typeof m === 'object' && typeof m.slug === 'string' && m.slug;
    }).map(function (m) {
      return {
        slug: m.slug,
        kind: m.kind === 'image' ? 'image' : 'video',
        mode: typeof m.mode === 'string' ? m.mode : '',
        from: typeof m.from === 'string' ? m.from : 'account'
      };
    });
    return out.length ? out : null;
  }

  /* A catalog can arrive from a file somebody else wrote, so it is checked
   * rather than trusted: one malformed value used to be stored and then
   * thrown on every later read, which took Settings down for good — in
   * localStorage, so closing the file did not help. */
  function storeCatalog(list) {
    const clean = cleanCatalog(list);
    if (!clean) return false;
    const all = lsGet(K_CAT) || {};
    all[catKey()] = { at: Date.now(), list: clean };
    lsSet(K_CAT, all);
    return true;
  }

  /* Ask the account what it offers, and say what moved. Called on sign-in, by
   * the Refresh button, when Settings opens on a stale cache, and when a push
   * is refused for a slug the account does not know — that refusal is the
   * catalog telling us it has changed. */
  function refreshCatalog() {
    if (transport() === 'key') {
      /* The account's tools describe the MCP surface; storing those names
       * against the API key would offer the v2 datalist models it has never
       * heard of. */
      const e = new Error('The API-key transport uses the v2 REST list, which is built in. ' +
        'Sign in to read your account\u2019s own models.');
      e.soft = true;
      return Promise.reject(e);
    }
    if (!isSignedIn()) {
      return Promise.reject(new Error('Sign in and this becomes whatever your account offers.'));
    }
    const was = (cachedCatalog() || {}).list || [];
    return toolList(true).then(function () {
      const now = fromAccount();
      if (!now.length) {
        /* Tools with no enum is not an empty catalog. */
        const e = new Error('Your account\u2019s tools do not publish a model list, so the ' +
          'built-in one stands.');
        e.soft = true;
        throw e;
      }
      storeCatalog(now);
      const had = {};
      was.forEach(function (x) { had[x.slug] = 1; });
      const has = {};
      now.forEach(function (x) { has[x.slug] = 1; });
      return {
        list: now, at: Date.now(),
        added: now.filter(function (x) { return was.length && !had[x.slug]; })
          .map(function (x) { return x.slug; }),
        gone: was.filter(function (x) { return !has[x.slug]; }).map(function (x) { return x.slug; })
      };
    });
  }

  function catalogAge() {
    const c = cachedCatalog();
    return c ? Date.now() - c.at : null;
  }

  /* Where the list on screen came from, so nobody mistakes my notes for their
   * account. */
  function catalogSource() {
    const c = cachedCatalog();
    if (c && c.list && c.list.length) return 'account';
    return (SB.ImagineModels && SB.ImagineModels.list && SB.ImagineModels.list.length)
      ? 'shipped' : 'fallback';
  }

  function catalogAll() {
    const c = cachedCatalog();
    const cached = c && Array.isArray(c.list) && c.list.length ? c.list : null;
    const base = cached || shipped();
    /* Proven slugs first, and never dropped for being absent from a list. */
    const proven = worked();
    if (!proven.length) return base;
    const have = {};
    proven.forEach(function (x) { have[x.slug] = 1; });
    return proven.concat(base.filter(function (m) { return !have[m.slug]; }));
  }

  /* Every model of a kind, most useful first — the account's own, then the
   * shipped list for anything it did not mention. */
  function catalog(kind) {
    return catalogAll()
      .filter(function (m) { return !kind || m.kind === kind; })
      .map(function (m) { return m.slug; });
  }

  /* ---------------- what has actually worked ----------------
   *
   * Every published list is behind the product — the v2 API's by a year, the
   * documentation's by months — and imagine.art is an aggregator, so the set
   * of models it carries moves whenever a third party ships one. FLUX 3 and
   * Veo are on the platform and in neither list.
   *
   * The one source that cannot be stale is a generation that worked. A slug
   * that produced something is recorded against the account and offered from
   * then on, whatever any catalog says — so the app converges on what is
   * true for the person using it rather than on what somebody published. */
  function worked() {
    const all = lsGet(K_WORKED) || {};
    return all[catKey()] || [];
  }

  function noteWorked(slug, kind) {
    const s = String(slug || '').trim();
    if (!s) return;
    const all = lsGet(K_WORKED) || {};
    const mine = all[catKey()] || [];
    const at = mine.filter(function (x) { return x.slug === s; })[0];
    if (at) { at.at = Date.now(); at.n = (at.n | 0) + 1; return void save(); }
    /* Keep what is already known about this slug — proving one works must
     * not erase which way round it runs, which is what the text-to-video
     * guard reads. */
    const known = modelInfo(s) || {};
    mine.push({
      slug: s, kind: kind || known.kind, mode: known.mode || '', deflt: !!known.deflt,
      at: Date.now(), n: 1, from: 'worked'
    });
    save();
    function save() {
      all[catKey()] = mine;
      lsSet(K_WORKED, all);
    }
  }

  function modelInfo(slug) {
    const s = String(slug || '').trim();
    if (!s) return null;
    return catalogAll().filter(function (m) { return m.slug === s; })[0] || null;
  }

  /* ---------------- the connection, step by step ----------------
   *
   * "It didn't work" is the least useful sentence in software, and a toast
   * that says why and then vanishes after two seconds is how you get it. This
   * walks the whole path — signed in, discovery, token, handshake, tools —
   * and reports each step as it goes, so a failure names the step, the
   * status and the message instead of disappearing.
   *
   * Never rejects: a broken connection is the thing being described. */
  function report() {
    const steps = [];
    const add = function (name, ok, detail) { steps.push({ name: name, ok: ok, detail: detail || '' }); };
    const bail = function (name) {
      return function (e) {
        add(name, false, (e && e.message) || String(e));
        const stop = new Error('stopped');
        stop.stopped = true;
        throw stop;
      };
    };

    if (transport() === 'key') {
      add('Transport', true, 'API key — MCP is not used, so there are no tools to list. ' +
        'Switch to “Sign in with ImagineArt” above to see an account’s own tools.');
      add('API key', !!apiKey(), apiKey() ? 'set in this browser' : 'none set');
      return Promise.resolve(steps);
    }

    add('Signed in', isSignedIn(),
      isSignedIn() ? ((tokens() || {}).email || 'yes') : 'no — press Sign in first');
    if (!isSignedIn()) return Promise.resolve(steps);

    return discover().then(function (meta) {
      add('Discovery', !!(meta && meta.token_endpoint), (meta && meta.issuer) || 'no metadata');
      return accessToken();
    }, bail('Discovery')).then(function () {
      const t = tokens() || {};
      const left = Math.round(((t.expires_at || 0) - Date.now()) / 60000);
      add('Access token', true, left > 0 ? 'good for ' + left + ' more minutes' : 'refreshed');
      return mcpReady();
    }, bail('Access token')).then(function (r) {
      const si = r && r.serverInfo;
      add('MCP handshake', true, si ? ((si.name || 'server') + ' ' + (si.version || '')).trim()
        : 'accepted');
      return toolList(true);
    }, function (e) {
      add('MCP handshake', false, ((e && e.message) || String(e)) +
        (e && e.cors ? ' — nothing was sent, so nothing was billed.' : '') +
        (e && e.status ? ' (HTTP ' + e.status + ')' : ''));
      const stop = new Error('stopped');
      stop.stopped = true;
      throw stop;
    }).then(function (list) {
      add('Tools', !!(list && list.length), (list || []).length + ' offered');
      const rest = lsStr(K_REST);
      if (rest) {
        add('v2 REST fallback', rest === 'yes',
          rest === 'yes' ? 'your token is accepted there too' : 'your token is not accepted there');
      }
      const named = [TOOL.image, TOOL.video, TOOL.status].filter(toolNamed);
      add('The tools this app uses', named.length === 3,
        named.length === 3
          ? TOOL.image + ', ' + TOOL.video + ', ' + TOOL.status
          : 'missing: ' + [TOOL.image, TOOL.video, TOOL.status].filter(function (n) {
            return !toolNamed(n);
          }).join(', '));
      const o = org();
      add('Organization', !!o, o ? (o.name || o.id) + ' — every generation is billed to it'
        : 'not chosen yet; nothing can be generated until it is');
      return steps;
    }, function (e) {
      if (!e || !e.stopped) add('Tools', false, (e && e.message) || String(e));
      return steps;
    }).catch(function () { return steps; });
  }

  /* Everything the account's tools say about themselves, flattened for
   * reading. The whole question of which models an OAuth session can reach —
   * and whether it can even be asked for one — is answered by this and
   * nothing else, and it cannot be answered from outside an account at all.
   * So it is one button rather than a support thread. */
  function capabilities() {
    return toolList(true).then(function (tools) {
      return (tools || []).map(function (t) {
        const ps = props(t);
        const req = (t.inputSchema && t.inputSchema.required) || [];
        return {
          name: t.name,
          description: t.description || '',
          takesImage: hasImageParam(t),
          params: Object.keys(ps).map(function (k) {
            const spec = ps[k] || {};
            return {
              name: k,
              type: spec.type || '',
              required: req.indexOf(k) >= 0,
              enum: Array.isArray(spec.enum) ? spec.enum.slice() : null,
              isModel: SYNONYM.slug.test(k)
            };
          })
        };
      });
    });
  }

  /* ---------------- why a push cannot run ----------------
   *
   * Lives here rather than in the prompt table because it is about the push,
   * and there are now three places that need the same answer in the same
   * words: the table's row, the clip review, and anything after them.
   *
   * Row reasons come before account reasons. The account one is identical on
   * every row and the chip already carries it; the row one is the entire
   * reason one card differs from the one beside it.
   */
  /* What a push of this shot will actually hand over, in words, so it can be
   * said on the button rather than discovered in the result.
   *
   * A still carries one reference and a card routinely feeds three; the
   * prompt's numbered mapping describes all of them as supplied. That gap is
   * the thing nobody could see. */
  function refsFor(p, shot, role) {
    const feed = SB.Refs.images(p, shot, role);
    /* Subjects on the card that have no reference frame of their own. They
       reach the model as words and nothing else, and looking at the card there
       is no way to tell them from the ones that do. */
    const named = SB.Refs.feed(p, shot, role).filter(function (e) { return e.kind === 'subject'; });
    const wordsOnly = named.filter(function (e) { return !e.images.length; }).length;
    const carries = role === 'image'
      ? (transport() === 'key' ? 0 : 1)
      : 1;
    return {
      feed: feed.length,
      wordsOnly: wordsOnly,
      carries: Math.min(carries, feed.length),
      first: feed[0] || null,
      byKey: transport() === 'key'
    };
  }

  function whyNot(p, shot, model, role) {
    const field = role === 'image' ? 'imagePrompt' : 'videoPrompt';
    if (!model) {
      return { short: 'no model', long: 'No ' + role + ' model is selected for this board.' };
    }
    if (shot.noShot) {
      return { short: 'no shot', long: 'A \u201cno shot\u201d card is never generated.' };
    }
    const gate = blocker(model);
    const gateNote = gate ? {
      short: /signed in/.test(gate) ? 'sign in'
        : /organization/.test(gate) ? 'pick an org'
          : /API key/.test(gate) ? 'no key' : 'no model set',
      long: gate
    } : null;
    const pr = (shot.prompts || {})[model.id] || null;
    if (pr && (pr[field] || '').trim()) return gateNote;

    const others = Object.keys(shot.prompts || {}).filter(function (id) {
      return id !== model.id && ((shot.prompts[id] || {})[field] || '').trim();
    }).map(function (id) {
      const other = SB.Model.modelById(p, id);
      return (other && other.name) || (shot.prompts[id] || {}).modelName || 'another model';
    });
    if (others.length) {
      return {
        short: 'written for ' + others[0],
        long: 'This shot has a ' + (role === 'image' ? 'first-frame' : 'video') + ' prompt, but ' +
          'it was written for ' + others.join(' and ') + ' — and the model chosen here is ' +
          model.name + '. Prompts are kept per model because each one wants different ' +
          'wording. Switch the model, or write one for ' + model.name + '.'
      };
    }
    return {
      short: 'no prompt yet',
      long: 'Nothing to send: write the ' + (role === 'image' ? 'first-frame' : 'video') +
        ' prompt for ' + model.name + ' first, in the Prompts panel.'
    };
  }

  /* The prompt a generated thing was made from. `made` carries the model id,
   * which is the only stable handle — names are free text, two models can
   * share one, and renaming or deleting one used to turn this silently
   * blank. Assets generated before the id was recorded fall back to the
   * name. Shared by the export manifest and the clip review. */
  function promptFor(p, shot, made) {
    if (!made) return null;
    const models = (p.settings && p.settings.models) || [];
    let m = made.modelId
      ? models.filter(function (x) { return x.id === made.modelId; })[0]
      : null;
    if (!m && made.model) {
      const named = models.filter(function (x) { return x.name === made.model; });
      if (named.length === 1) m = named[0];
      else if (named.length > 1) return '(several models share that name — cannot say which)';
    }
    if (!m) return '(that model is no longer on this board)';
    const pr = shot.prompts && shot.prompts[m.id];
    if (!pr) return '';
    return (made.role === 'video' ? pr.videoPrompt : pr.imagePrompt) || '';
  }

  /* How long it runs and how big it is, read off the file itself. Worth the
   * round trip: a badge that says "2s" is the difference between a card that
   * has something and a card whose clip you have to open to identify.
   * Failing to read it is not a failure to keep it. */
  function clipMeta(blob) {
    return new Promise(function (resolve) {
      let url = '';
      let done = false;
      const finish = function (meta) {
        if (done) return;
        done = true;
        if (url) URL.revokeObjectURL(url);
        resolve(meta || {});
      };
      try {
        url = URL.createObjectURL(blob);
        const v = document.createElement('video');
        v.preload = 'metadata';
        v.onloadedmetadata = function () {
          finish({
            dur: isFinite(v.duration) ? Math.round(v.duration * 10) / 10 : 0,
            w: v.videoWidth || 0, h: v.videoHeight || 0
          });
        };
        v.onerror = function () { finish(null); };
        v.src = url;
      } catch (e) { finish(null); }
      setTimeout(function () { finish(null); }, 4000);
    });
  }

  /* A clip made somewhere else — rendered last month, cut in Premiere,
   * handed over by somebody — put on a card. Nothing generated it here, so
   * it carries no `made` and the export's "only what was made in here"
   * filter correctly passes it by. */
  function attachClip(p, shot, file) {
    if (!file) return Promise.resolve(null);
    if (!/^video\//.test(file.type || '')) {
      return Promise.reject(new Error('That is not a video file.'));
    }
    return clipMeta(file).then(function (meta) {
      /* Same rule as a generated one: a card holds its takes -- and nothing
         moves until there is a record to move to, or a file that turns out to
         be unreadable takes every take on the card out of reach. */
      return SB.Renders.keepVideo(p, file, null).then(function (saved) {
        if (!saved) throw new Error('the clip could not be stored');
        if (meta.dur) saved.dur = meta.dur;
        if (meta.w) { saved.w = meta.w; saved.h = meta.h; }
        saved.name = file.name || '';
        SB.Model.addTake(shot, saved);
        SB.app.changed(true);
        return saved;
      });
    });
  }

  /* One take, or the lot. Removing the chosen one promotes the newest of what
   * is left rather than leaving a card holding none while still carrying two. */
  function dropClip(p, shot, rec) {
    if (!shot || !shot.video) return;
    if (rec) SB.Model.dropTake(shot, rec);
    else { shot.video = null; shot.videoAlts = []; }
    SB.app.changed(true);
  }

  /* "2s · 1184×672 · 1.9 MB", as much of it as is known. */
  function clipLabel(rec) {
    if (!rec) return '';
    const bits = [];
    if (rec.dur) bits.push(rec.dur + 's');
    if (rec.w) bits.push(rec.w + '×' + rec.h);
    if (rec.bytes) bits.push((rec.bytes / 1048576).toFixed(1) + ' MB');
    if (!rec.ref) bits.push('link only');
    return bits.join(' · ');
  }

  /* ---------------- looking at a clip ----------------
   *
   * One modal, opened from the card and from the prompt table, and the same
   * one whether the shot has a clip or not — because "is there one, and
   * what is it" is a single question and it used to be answered by two
   * buttons that did different things, one of which opened a file dialog
   * with no warning.
   *
   * A clip is the only thing on a board with no thumbnail of its own: the
   * card shows the still either way. So this is where it gets looked at,
   * and everything known about it is here rather than spread between a
   * tooltip and the export manifest.
   */
  function codeOf(p, shot) {
    const f = SB.Model.findShot(p, shot.id);
    return f ? f.code : '';
  }

  function describeMade(p, shot, rec) {
    const made = rec && rec.made;
    if (!made) {
      return rec ? 'Added from a file' + (rec.name ? ' (' + rec.name + ')' : '') +
        ' — nothing here generated it, so an export of “what was made in here” passes it by.'
        : '';
    }
    const when = made.at ? ' on ' + new Date(made.at).toLocaleDateString() : '';
    const res = made.resolution ? ' at ' + made.resolution : '';
    const cost = costFor(made.slug || '', '', made.resolution || '');
    /* Which picture went with it, because "it ignored the reference" and "it
       was never sent one" look identical in the result. */
    const ref = made.reference
      ? ' Sent with \u201c' + (made.reference.label || 'a reference') + '\u201d' +
        (made.reference.of > 1 ? ' (1 of ' + made.reference.of + ' the card feeds)' : '') + '.'
      : '';
    return 'Made here' + when + ' by ' + (made.model || made.slug || 'a model') + res +
      (cost ? ', about ' + cost.credits + ' credits' : '') + '.' + ref;
  }

  function openClip(p, shot) {
    const rec = shot && shot.video;
    const model = SB.Model.videoModel(p);

    /* Opening this is watching it — the clip autoplays below. Painted in
     * place rather than by a rebuild: the prompt table this is usually opened
     * from has boxes in it that somebody may be typing in. */
    if (rec && rec.unseen) {
      delete rec.unseen;
      SB.Store.touch();
      notify();
    }
    const box = SB.el('div', 'clip-box');
    let objectUrl = '';
    let m = null;

    const close = function () { if (m) m.close(); };

    const mount = function (file) {
      if (rec && (file || rec.url)) {
        const v = document.createElement('video');
        objectUrl = file ? URL.createObjectURL(file) : '';
        v.src = objectUrl || rec.url;
        v.controls = true;
        v.autoplay = true;
        v.loop = true;
        box.appendChild(v);
        if (!file && rec.url) {
          const note = SB.el('div', 'pp-note warn',
            'Played from ImagineArt — this board has no copy of its own, and that link ' +
            'expires. ');
          const grab = SB.el('button', 'mini', 'bring it into the board');
          grab.onclick = function () {
            grab.disabled = true;
            grab.textContent = 'fetching…';
            fetchClip(shot).then(function (ok) {
              SB.toast(ok ? 'Clip is in the board now' : 'Nothing to fetch');
              close();
            }).catch(function (e) {
              grab.disabled = false;
              grab.textContent = 'bring it into the board';
              SB.toast(e.message, true);
            });
          };
          note.appendChild(grab);
          box.appendChild(note);
        }
      } else if (!rec) {
        /* no clip: the still stands in, so the card is recognisable */
        const src = shot.image ? SB.Blobs.src(p, shot.image) : '';
        if (src) {
          const im = document.createElement('img');
          im.src = src;
          im.className = 'clip-still';
          box.appendChild(im);
        }
        box.appendChild(SB.el('div', 'pp-note',
          'No clip on this card yet. Shoot one from the video prompt, or add a file you ' +
          'already have — dropping an mp4 straight onto the card does the same thing.'));
      } else {
        box.appendChild(SB.el('div', 'pp-note warn',
          'This board has no copy of that clip and its link has gone.'));
      }

      /* Every take this card holds, with the chosen one marked. This is the
         whole feature from the user's side: the one that was mostly right is
         still here, and one click makes it the keeper again. */
      const all = SB.Model.takes(shot);
      if (all.length > 1) {
        const strip = SB.el('div', 'clip-takes');
        strip.appendChild(SB.el('div', 'pp-note',
          all.length + ' takes on this card. The chosen one is what the board shows, ' +
          'what a push replaces, and what an export calls the pick.'));
        all.forEach(function (tk) {
          const row = SB.el('div', 'clip-take' + (tk.chosen ? ' on' : ''));
          row.appendChild(SB.el('span', 'tk-n', 'take ' + tk.n));
          row.appendChild(SB.el('span', 'tk-what',
            (clipLabel(tk.rec) || 'a clip') +
            (tk.rec.made ? ' \u00b7 ' + (tk.rec.made.model || tk.rec.made.slug || 'made here')
                         : ' \u00b7 added from a file')));
          row.appendChild(SB.el('span', 'spacer'));
          if (tk.chosen) {
            row.appendChild(SB.el('span', 'badge done', 'chosen'));
          } else {
            const use = SB.el('button', 'mini primary', 'use this one');
            use.title = 'Make this the take the board shows and the export picks.';
            use.onclick = function () {
              SB.Model.useTake(shot, tk.rec);
              SB.Store.touch();
              close();
              SB.app.changed(true);
              SB.toast('Take ' + tk.n + ' is the one on ' + (codeOf(p, shot) || 'the card'));
            };
            row.appendChild(use);
          }
          const rm = SB.el('button', 'mini danger', 'remove');
          rm.title = 'Delete this take. The bytes go with it.';
          SB.armButton(rm, 'delete take ' + tk.n, function () {
            const wasChosen = tk.chosen;
            dropClip(p, shot, tk.rec);
            close();
            SB.toast('Take ' + tk.n + ' removed' +
              (wasChosen ? ' \u2014 the newest of the rest is chosen now' : ''));
          });
          row.appendChild(rm);
          strip.appendChild(row);
        });
        box.appendChild(strip);
      }

      if (rec) {
        const line = clipLabel(rec);
        if (line) {
          box.appendChild(SB.el('div', 'pp-note', line +
            (rec.serial ? ' · ' + SB.Renders.fileName(rec.serial, rec.ext) : '')));
        }
        box.appendChild(SB.el('div', 'pp-note', describeMade(p, shot, rec)));
        const prompt = promptFor(p, shot, rec.made);
        if (prompt) {
          const q = SB.el('div', 'clip-prompt', '“' + prompt + '”');
          q.title = 'The video prompt on this card now — it may have been edited since.';
          box.appendChild(q);
        }
      }

      /* what can be done from here */
      const acts = SB.el('div', 'pp-actions');
      const why = whyNot(p, shot, model, 'video');

      const shoot = SB.el('button', 'tb' + (rec ? '' : ' on'),
        rec ? 'Shoot another take' : 'Shoot it');
      shoot.disabled = !!why;
      shoot.title = why ? why.long
        : 'Send the video prompt to ' + (model && model.name) + '.' +
          (rec ? ' What is here is kept as another take.' : '');
      shoot.onclick = function () {
        close();
        confirmCost(p, shot, model, function () {
          SB.toast('Shooting ' + (codeOf(p, shot) || 'this shot') + '…');
          run(shot, 'video').then(function () {
            SB.toast('Clip ready on ' + (codeOf(p, shot) || 'the card'));
          }).catch(function (e) { SB.toast(e.message, true); });
        });
      };
      acts.appendChild(shoot);

      const add = SB.el('button', 'tb', rec ? 'Add another take…' : 'Add from a file…');
      add.title = 'Put a file you already have on this card.' +
        (rec ? ' What is here is kept as another take.' : '');
      add.onclick = function () {
        SB.pickVideoFile().then(function (file) {
          if (!file) return;
          close();
          return attachClip(p, shot, file).then(function (saved) {
            SB.toast((rec ? 'Another take added' : 'Clip added') +
              (clipLabel(saved) ? ' · ' + clipLabel(saved) : ''));
          });
        }).catch(function (e) { SB.toast(e.message || String(e), true); });
      };
      acts.appendChild(add);

      if (rec) {
        const many = SB.Model.takeCount(shot) > 1;
        const rm = SB.el('button', 'tb danger', many ? 'Remove all takes' : 'Remove');
        rm.title = many
          ? 'Take every one of them off this card. The bytes go with them.'
          : 'Take the clip off this card. The bytes go with it.';
        SB.armButton(rm, many ? 'remove all for good' : 'remove for good', function () {
          dropClip(p, shot);
          SB.toast(many ? 'All takes removed' : 'Clip removed');
          close();
        });
        acts.appendChild(rm);
      }
      box.appendChild(acts);

      if (why) {
        box.appendChild(SB.el('div', 'pp-note warn', why.long));
      }

      m = SB.modal({
        title: 'Clip' + (codeOf(p, shot) ? ' · ' + codeOf(p, shot) : ''),
        width: '760px',
        body: box,
        buttons: [{ label: 'Close', primary: true }],
        onClose: function () {
          const v = box.querySelector('video');
          if (v) v.pause();
          if (objectUrl) URL.revokeObjectURL(objectUrl);
        }
      });
    };

    if (rec && rec.ref) SB.Renders.videoFile(p, rec).then(mount);
    else mount(null);
  }

  /* A clip is the expensive one, and the moment before it goes is the only
   * moment the number is any use. Asked once per session, from wherever the
   * push was started. */
  let costAsked = false;

  function confirmCost(p, shot, model, then) {
    const slug = slugOf(model);
    const res = resolutionFor(p, slug, 'video');
    const c = slug ? costFor(slug, '', res) : null;
    if (costAsked) { then(); return; }
    /* No price for this one is not an answer to the question — latching here
     * meant one unpriced model silenced the confirmation for every clip
     * after it, including a nine-hundred-credit one. */
    if (!c || !c.credits) { then(); return; }
    const acct = account();
    const bal = acct && typeof acct.credits === 'number' ? acct.credits : null;
    const body = SB.el('div');
    body.appendChild(SB.el('p', null,
      model.name + ' at ' + (res || 'its default resolution') + ' — about ' + c.credits +
      ' credits' + (c.from === 'measured' ? ', which is what it cost last time.'
        : '. That is the published base price; a longer or larger clip costs more.')));
    if (bal !== null) {
      body.appendChild(SB.el('p', 'pp-note' + (bal < c.credits ? ' warn' : ''),
        'You have ' + bal + ' credits' + (bal < c.credits ? ' — this may not go through.' : '.')));
    }
    body.appendChild(SB.el('div', 'pp-note',
      'Asked once per session; every clip after this goes straight through.'));
    SB.modal({
      title: 'Shoot this clip?', width: '420px', body: body,
      buttons: [
        { label: 'Cancel' },
        {
          label: 'Shoot it', primary: true, onClick: function (cl) {
            costAsked = true;
            cl();
            then();
          }
        }
      ]
    });
  }

